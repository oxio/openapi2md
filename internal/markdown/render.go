package markdown

import (
	"fmt"
	"slices"
	"sort"
	"strconv"
	"strings"

	"github.com/oxio/openapi2md/internal/openapi"
)

// DefaultHeader is the default generated-file comment emitted at the top of the Markdown output.
const DefaultHeader = "<!-- Code generated by openapi2md; DO NOT EDIT. -->"

// Options configures Markdown rendering behavior.
type Options struct {
	Header    string
	NoHeader  bool
	Title     string
	SpecURL   string
	TOC       bool
	NoSchemas bool
}

// Render converts an OpenAPI Document into deterministic GitHub-flavored Markdown.
func Render(doc *openapi.Document, opts Options) (string, error) {
	if doc == nil {
		return "", fmt.Errorf("nil OpenAPI document")
	}
	r := &renderer{
		doc:           doc,
		opts:          opts,
		usedAnchors:   make(map[string]bool),
		schemaAnchors: make(map[string]string),
		schemaTitles:  make(map[string]string),
	}
	return r.render()
}

type renderer struct {
	doc           *openapi.Document
	opts          Options
	usedAnchors   map[string]bool
	schemaAnchors map[string]string
	schemaTitles  map[string]string
}

type opEntry struct {
	path        string
	method      string
	op          *openapi.Operation
	pathParams  []openapi.Parameter
	pathServers []openapi.Server
}

type tagGroup struct {
	name         string
	heading      string
	anchor       string
	description  string
	externalDocs *openapi.ExternalDocs
	ops          []opEntry
}

func (r *renderer) allocHeading(preferred string) (heading, anchor string) {
	base := Anchor(preferred)
	if !r.usedAnchors[base] {
		r.usedAnchors[base] = true
		return preferred, base
	}
	for i := 2; ; i++ {
		candidate := fmt.Sprintf("%s (%d)", preferred, i)
		a := Anchor(candidate)
		if !r.usedAnchors[a] {
			r.usedAnchors[a] = true
			return candidate, a
		}
	}
}

func (r *renderer) render() (string, error) {
	// 1. Collect and decode all path operations first so any malformed operation fails early.
	groups, err := r.collectPathGroups()
	if err != nil {
		return "", err
	}
	webhookOps, err := r.collectWebhooks()
	if err != nil {
		return "", err
	}

	// 2. Reserve headings and anchors in document order so schema links always target
	// unique, valid headings with zero anchor collisions.
	title := strings.TrimSpace(r.opts.Title)
	if title == "" {
		title = strings.TrimSpace(r.doc.Info.Title)
	}
	r.allocHeading(title)

	var tocItems []struct {
		title  string
		anchor string
	}
	if r.opts.TOC {
		r.allocHeading("Table of Contents")
	}

	var serversHeading string
	if len(r.doc.Servers) > 0 {
		var serversAnchor string
		serversHeading, serversAnchor = r.allocHeading("Servers")
		tocItems = append(tocItems, struct{ title, anchor string }{serversHeading, serversAnchor})
	}

	var authHeading string
	hasAuth := (r.doc.Components != nil && len(r.doc.Components.SecuritySchemes) > 0) || len(r.doc.Security) > 0
	if hasAuth {
		var authAnchor string
		authHeading, authAnchor = r.allocHeading("Authentication")
		tocItems = append(tocItems, struct{ title, anchor string }{authHeading, authAnchor})
	}

	for i := range groups {
		groups[i].heading, groups[i].anchor = r.allocHeading(groups[i].name)
		tocItems = append(tocItems, struct{ title, anchor string }{groups[i].heading, groups[i].anchor})
		for _, entry := range groups[i].ops {
			opTitle := fmt.Sprintf("%s %s", strings.ToUpper(entry.method), entry.path)
			r.allocHeading(opTitle)
		}
	}

	var webhooksHeading string
	if len(webhookOps) > 0 {
		var webhooksAnchor string
		webhooksHeading, webhooksAnchor = r.allocHeading("Webhooks")
		tocItems = append(tocItems, struct{ title, anchor string }{webhooksHeading, webhooksAnchor})
		for _, entry := range webhookOps {
			opTitle := fmt.Sprintf("%s %s", strings.ToUpper(entry.method), entry.path)
			r.allocHeading(opTitle)
		}
	}

	var schemasHeading string
	var schemaNames []string
	if !r.opts.NoSchemas && r.doc.Components != nil && len(r.doc.Components.Schemas) > 0 {
		var schemasAnchor string
		schemasHeading, schemasAnchor = r.allocHeading("Schemas")
		tocItems = append(tocItems, struct{ title, anchor string }{schemasHeading, schemasAnchor})
		schemaNames = sortedKeys(r.doc.Components.Schemas)
		for _, name := range schemaNames {
			preferred := name
			if r.usedAnchors[Anchor(preferred)] {
				preferred = name + " (Schema)"
			}
			heading, anchor := r.allocHeading(preferred)
			r.schemaTitles[name] = heading
			r.schemaAnchors[name] = anchor
		}
	}

	// 3. Emit Markdown.
	var b strings.Builder

	if !r.opts.NoHeader {
		header := r.opts.Header
		if header == "" {
			header = DefaultHeader
		}
		b.WriteString(header)
		b.WriteString("\n\n")
	}

	b.WriteString("# ")
	b.WriteString(title)
	b.WriteString("\n\n")

	if r.doc.Info.Version != "" {
		fmt.Fprintf(&b, "Version %s, OpenAPI %s.\n", r.doc.Info.Version, r.doc.OpenAPI)
	} else {
		fmt.Fprintf(&b, "OpenAPI %s.\n", r.doc.OpenAPI)
	}
	if r.opts.SpecURL != "" {
		fmt.Fprintf(&b, "\nOpenAPI specification: `%s`.\n", r.opts.SpecURL)
	}
	if summary := strings.TrimSpace(r.doc.Info.Summary); summary != "" {
		fmt.Fprintf(&b, "\n%s\n", summary)
	}
	if desc := strings.TrimSpace(r.doc.Info.Description); desc != "" {
		fmt.Fprintf(&b, "\n%s\n", desc)
	}

	r.renderInfoMetadata(&b)

	if r.opts.TOC && len(tocItems) > 0 {
		b.WriteString("\n## Table of Contents\n\n")
		for _, item := range tocItems {
			fmt.Fprintf(&b, "- [%s](#%s)\n", item.title, item.anchor)
		}
	}

	if len(r.doc.Servers) > 0 {
		fmt.Fprintf(&b, "\n## %s\n\n", serversHeading)
		r.renderServers(&b, r.doc.Servers)
	}

	if hasAuth {
		fmt.Fprintf(&b, "\n## %s\n\n", authHeading)
		r.renderAuthentication(&b)
	}

	for _, g := range groups {
		fmt.Fprintf(&b, "\n## %s\n", g.heading)
		if desc := strings.TrimSpace(g.description); desc != "" {
			fmt.Fprintf(&b, "\n%s\n", desc)
		}
		if g.externalDocs != nil && g.externalDocs.URL != "" {
			fmt.Fprintf(&b, "\n%s\n", formatExternalDocs(g.externalDocs))
		}
		for _, entry := range g.ops {
			r.renderOperation(&b, entry)
		}
	}

	if len(webhookOps) > 0 {
		fmt.Fprintf(&b, "\n## %s\n", webhooksHeading)
		for _, entry := range webhookOps {
			r.renderOperation(&b, entry)
		}
	}

	if len(schemaNames) > 0 {
		fmt.Fprintf(&b, "\n## %s\n", schemasHeading)
		for _, name := range schemaNames {
			r.renderSchemaSection(&b, name, r.doc.Components.Schemas[name])
		}
	}

	return strings.TrimRight(b.String(), "\n") + "\n", nil
}

func (r *renderer) collectPathGroups() ([]tagGroup, error) {
	var allOps []opEntry
	paths := sortedKeys(r.doc.Paths)
	for _, p := range paths {
		pi := r.doc.ResolvePathItem(r.doc.Paths[p])
		for _, method := range openapi.HTTPMethods {
			op, err := pi.DecodeOperation(method, p)
			if err != nil {
				return nil, err
			}
			if op == nil {
				continue
			}
			allOps = append(allOps, opEntry{
				path:        p,
				method:      method,
				op:          op,
				pathParams:  pi.Parameters,
				pathServers: pi.Servers,
			})
		}
	}

	// Build tag metadata map and declared order.
	declaredOrder := make([]string, 0, len(r.doc.Tags))
	tagMeta := make(map[string]openapi.Tag, len(r.doc.Tags))
	for _, t := range r.doc.Tags {
		if _, seen := tagMeta[t.Name]; !seen {
			declaredOrder = append(declaredOrder, t.Name)
		}
		tagMeta[t.Name] = t
	}

	byTag := make(map[string][]opEntry)
	var untagged []opEntry
	extraTagsSet := make(map[string]bool)

	for _, entry := range allOps {
		if len(entry.op.Tags) == 0 {
			untagged = append(untagged, entry)
			continue
		}
		// Place under first tag (avoids duplicate operation headings across sections).
		tag := entry.op.Tags[0]
		byTag[tag] = append(byTag[tag], entry)
		if _, declared := tagMeta[tag]; !declared {
			extraTagsSet[tag] = true
		}
	}

	extraTags := sortedKeys(extraTagsSet)
	var groups []tagGroup

	for _, name := range declaredOrder {
		ops := byTag[name]
		if len(ops) == 0 {
			continue
		}
		sortOps(ops)
		meta := tagMeta[name]
		groups = append(groups, tagGroup{
			name:         name,
			description:  meta.Description,
			externalDocs: meta.ExternalDocs,
			ops:          ops,
		})
	}
	for _, name := range extraTags {
		ops := byTag[name]
		sortOps(ops)
		groups = append(groups, tagGroup{
			name: name,
			ops:  ops,
		})
	}
	if len(untagged) > 0 {
		sortOps(untagged)
		groups = append(groups, tagGroup{
			name: "Other",
			ops:  untagged,
		})
	}
	return groups, nil
}

func (r *renderer) collectWebhooks() ([]opEntry, error) {
	if len(r.doc.Webhooks) == 0 {
		return nil, nil
	}
	var ops []opEntry
	names := sortedKeys(r.doc.Webhooks)
	for _, name := range names {
		pi := r.doc.ResolvePathItem(r.doc.Webhooks[name])
		for _, method := range openapi.HTTPMethods {
			op, err := pi.DecodeOperation(method, name)
			if err != nil {
				return nil, err
			}
			if op == nil {
				continue
			}
			ops = append(ops, opEntry{
				path:        name,
				method:      method,
				op:          op,
				pathParams:  pi.Parameters,
				pathServers: pi.Servers,
			})
		}
	}
	sortOps(ops)
	return ops, nil
}

func sortOps(ops []opEntry) {
	methodRank := make(map[string]int, len(openapi.HTTPMethods))
	for i, m := range openapi.HTTPMethods {
		methodRank[m] = i
	}
	sort.SliceStable(ops, func(i, j int) bool {
		if ops[i].path != ops[j].path {
			return ops[i].path < ops[j].path
		}
		return methodRank[ops[i].method] < methodRank[ops[j].method]
	})
}

func (r *renderer) renderInfoMetadata(b *strings.Builder) {
	var lines []string
	if r.doc.Info.TermsOfService != "" {
		lines = append(lines, fmt.Sprintf("- **Terms of Service:** %s", r.doc.Info.TermsOfService))
	}
	if c := r.doc.Info.Contact; c != nil && (c.Name != "" || c.Email != "" || c.URL != "") {
		var parts []string
		if c.Name != "" {
			parts = append(parts, c.Name)
		}
		if c.Email != "" {
			parts = append(parts, c.Email)
		}
		if c.URL != "" {
			parts = append(parts, c.URL)
		}
		lines = append(lines, fmt.Sprintf("- **Contact:** %s", strings.Join(parts, " — ")))
	}
	if l := r.doc.Info.License; l != nil && l.Name != "" {
		lic := l.Name
		if l.Identifier != "" {
			lic += " (" + l.Identifier + ")"
		}
		if l.URL != "" {
			lic = fmt.Sprintf("[%s](%s)", lic, l.URL)
		}
		lines = append(lines, fmt.Sprintf("- **License:** %s", lic))
	}
	if r.doc.ExternalDocs != nil && r.doc.ExternalDocs.URL != "" {
		lines = append(lines, "- "+formatExternalDocs(r.doc.ExternalDocs))
	}
	if len(lines) > 0 {
		b.WriteString("\n")
		for _, line := range lines {
			b.WriteString(line)
			b.WriteString("\n")
		}
	}
}

func formatExternalDocs(ed *openapi.ExternalDocs) string {
	label := strings.TrimSpace(ed.Description)
	if label == "" {
		label = ed.URL
	}
	return fmt.Sprintf("**External documentation:** [%s](%s)", label, ed.URL)
}

func (r *renderer) renderServers(b *strings.Builder, servers []openapi.Server) {
	for _, s := range servers {
		if desc := strings.TrimSpace(s.Description); desc != "" {
			fmt.Fprintf(b, "- `%s` — %s\n", s.URL, desc)
		} else {
			fmt.Fprintf(b, "- `%s`\n", s.URL)
		}
		if len(s.Variables) > 0 {
			for _, vName := range sortedKeys(s.Variables) {
				v := s.Variables[vName]
				line := fmt.Sprintf("  - `%s`: default `%s`", vName, v.Default)
				if len(v.Enum) > 0 {
					vals := make([]string, len(v.Enum))
					for i, ev := range v.Enum {
						vals[i] = "`" + ev + "`"
					}
					line += " (one of " + strings.Join(vals, ", ") + ")"
				}
				if d := strings.TrimSpace(v.Description); d != "" {
					line += " — " + d
				}
				b.WriteString(line + "\n")
			}
		}
	}
}

func (r *renderer) renderAuthentication(b *strings.Builder) {
	if r.doc.Components != nil && len(r.doc.Components.SecuritySchemes) > 0 {
		b.WriteString("| Scheme | Type | Details |\n")
		b.WriteString("| --- | --- | --- |\n")
		for _, name := range sortedKeys(r.doc.Components.SecuritySchemes) {
			s := r.doc.ResolveSecurityScheme(r.doc.Components.SecuritySchemes[name])
			details := formatSecuritySchemeDetails(s)
			fmt.Fprintf(b, "| `%s` | %s | %s |\n", escapeCell(name), escapeCell(s.Type), escapeCell(details))
		}
	}
	if len(r.doc.Security) > 0 {
		if r.doc.Components != nil && len(r.doc.Components.SecuritySchemes) > 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(b, "**Default security:** %s\n", formatSecurityRequirements(r.doc.Security))
	}
}

func formatSecuritySchemeDetails(s openapi.SecurityScheme) string {
	var parts []string
	switch s.Type {
	case "apiKey":
		parts = append(parts, fmt.Sprintf("`%s` in %s", s.Name, s.In))
	case "http":
		d := fmt.Sprintf("scheme `%s`", s.Scheme)
		if s.BearerFormat != "" {
			d += fmt.Sprintf(" (%s)", s.BearerFormat)
		}
		parts = append(parts, d)
	case "openIdConnect":
		if s.OpenIDConnectURL != "" {
			parts = append(parts, fmt.Sprintf("OpenID Connect URL: `%s`", s.OpenIDConnectURL))
		}
	case "oauth2":
		if s.Flows != nil {
			var flows []string
			if s.Flows.AuthorizationCode != nil {
				flows = append(flows, "authorizationCode")
			}
			if s.Flows.ClientCredentials != nil {
				flows = append(flows, "clientCredentials")
			}
			if s.Flows.Implicit != nil {
				flows = append(flows, "implicit")
			}
			if s.Flows.Password != nil {
				flows = append(flows, "password")
			}
			if len(flows) > 0 {
				parts = append(parts, "flows: "+strings.Join(flows, ", "))
			}
		}
	}
	if desc := strings.TrimSpace(s.Description); desc != "" {
		parts = append(parts, desc)
	}
	return strings.Join(parts, ". ")
}

func formatSecurityRequirements(reqs []openapi.SecurityRequirement) string {
	if len(reqs) == 0 {
		return "none (public)"
	}
	alts := make([]string, 0, len(reqs))
	for _, req := range reqs {
		if len(req) == 0 {
			alts = append(alts, "none")
			continue
		}
		var terms []string
		for _, name := range sortedKeys(req) {
			scopes := req[name]
			if len(scopes) > 0 {
				sc := make([]string, len(scopes))
				for i, s := range scopes {
					sc[i] = "`" + s + "`"
				}
				terms = append(terms, fmt.Sprintf("`%s` (%s)", name, strings.Join(sc, ", ")))
			} else {
				terms = append(terms, fmt.Sprintf("`%s`", name))
			}
		}
		alts = append(alts, strings.Join(terms, " + "))
	}
	return strings.Join(alts, " or ")
}

func (r *renderer) renderOperation(b *strings.Builder, entry opEntry) {
	op := entry.op
	fmt.Fprintf(b, "\n### %s %s\n", strings.ToUpper(entry.method), entry.path)

	if op.Deprecated {
		b.WriteString("\n*(Deprecated)*\n")
	}

	summary := strings.TrimSpace(op.Summary)
	opID := strings.TrimSpace(op.OperationID)
	switch {
	case summary != "" && opID != "":
		fmt.Fprintf(b, "\n**%s** (`%s`)\n", summary, opID)
	case summary != "":
		fmt.Fprintf(b, "\n**%s**\n", summary)
	case opID != "":
		fmt.Fprintf(b, "\n`%s`\n", opID)
	}

	if desc := strings.TrimSpace(op.Description); desc != "" {
		fmt.Fprintf(b, "\n%s\n", desc)
	}
	if op.ExternalDocs != nil && op.ExternalDocs.URL != "" {
		fmt.Fprintf(b, "\n%s\n", formatExternalDocs(op.ExternalDocs))
	}

	if op.Security != nil {
		fmt.Fprintf(b, "\n**Security:** %s\n", formatSecurityRequirements(*op.Security))
	}

	servers := op.Servers
	if len(servers) == 0 {
		servers = entry.pathServers
	}
	if len(servers) > 0 {
		b.WriteString("\n**Servers:**\n\n")
		r.renderServers(b, servers)
	}

	// Parameters (merge path-level and operation-level).
	params := r.mergeParameters(entry.pathParams, op.Parameters)
	if len(params) > 0 {
		b.WriteString("\n**Parameters**\n\n")
		b.WriteString("| Name | In | Type | Required | Description |\n")
		b.WriteString("| --- | --- | --- | --- | --- |\n")
		for _, p := range params {
			req := "no"
			if p.Required || p.In == "path" {
				req = "yes"
			}
			typ := r.parameterType(p)
			details := formatSchemaDetails(p.Description, p.Deprecated, p.Schema, p.Example, p.HasExample)
			fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s |\n",
				escapeCell(p.Name),
				escapeCell(p.In),
				escapeCell(typ),
				req,
				escapeCell(details),
			)
		}
	}

	// Request body.
	if rb := r.doc.ResolveRequestBody(op.RequestBody); rb != nil && len(rb.Content) > 0 {
		if rb.Required {
			b.WriteString("\n**Request body** (required)\n")
		} else {
			b.WriteString("\n**Request body**\n")
		}
		if desc := strings.TrimSpace(rb.Description); desc != "" {
			fmt.Fprintf(b, "\n%s\n", desc)
		}
		b.WriteString("\n")
		for _, ct := range sortedKeys(rb.Content) {
			mt := rb.Content[ct]
			fmt.Fprintf(b, "- `%s`: %s\n", ct, r.formatType(mt.Schema))
			if mt.Schema != nil && mt.Schema.Ref == "" && len(mt.Schema.Properties) > 0 {
				b.WriteString("\n")
				r.renderPropertiesTable(b, mt.Schema)
				b.WriteString("\n")
			}
		}
	}

	// Responses.
	if len(op.Responses) > 0 {
		b.WriteString("\n**Responses**\n\n")
		b.WriteString("| Status | Description | Content |\n")
		b.WriteString("| --- | --- | --- |\n")

		statuses := sortedStatuses(op.Responses)
		type respHeaderRow struct {
			status string
			name   string
			header openapi.Header
		}
		var headerRows []respHeaderRow

		for _, status := range statuses {
			resp := r.doc.ResolveResponse(op.Responses[status])
			content := r.formatResponseContent(resp.Content)
			fmt.Fprintf(b, "| %s | %s | %s |\n",
				escapeCell(status),
				escapeCell(strings.TrimSpace(resp.Description)),
				escapeCell(content),
			)
			if len(resp.Headers) > 0 {
				for _, hName := range sortedKeys(resp.Headers) {
					headerRows = append(headerRows, respHeaderRow{
						status: status,
						name:   hName,
						header: r.doc.ResolveHeader(resp.Headers[hName]),
					})
				}
			}
		}

		if len(headerRows) > 0 {
			b.WriteString("\n**Response headers**\n\n")
			b.WriteString("| Status | Header | Type | Required | Description |\n")
			b.WriteString("| --- | --- | --- | --- | --- |\n")
			for _, hr := range headerRows {
				req := "no"
				if hr.header.Required {
					req = "yes"
				}
				typ := r.formatType(hr.header.Schema)
				details := formatSchemaDetails(hr.header.Description, hr.header.Deprecated, hr.header.Schema, hr.header.Example, hr.header.HasExample)
				fmt.Fprintf(b, "| %s | `%s` | %s | %s | %s |\n",
					escapeCell(hr.status),
					escapeCell(hr.name),
					escapeCell(typ),
					req,
					escapeCell(details),
				)
			}
		}
	}

	// Callbacks.
	if len(op.Callbacks) > 0 {
		b.WriteString("\n**Callbacks**\n\n")
		for _, cbName := range sortedKeys(op.Callbacks) {
			cb := r.doc.ResolveCallback(op.Callbacks[cbName])
			for _, expr := range sortedKeys(cb.Paths) {
				pi := r.doc.ResolvePathItem(cb.Paths[expr])
				for _, method := range openapi.HTTPMethods {
					cbOp, err := pi.DecodeOperation(method, expr)
					if err != nil || cbOp == nil {
						continue
					}
					line := fmt.Sprintf("- **%s**: `%s %s`", cbName, strings.ToUpper(method), expr)
					if s := strings.TrimSpace(cbOp.Summary); s != "" {
						line += " — " + s
					}
					b.WriteString(line + "\n")
				}
			}
		}
	}
}

func (r *renderer) mergeParameters(pathParams, opParams []openapi.Parameter) []openapi.Parameter {
	type paramKey struct {
		in   string
		name string
	}
	merged := make(map[paramKey]openapi.Parameter)
	for _, p := range pathParams {
		rp := r.doc.ResolveParameter(p)
		merged[paramKey{in: rp.In, name: rp.Name}] = rp
	}
	for _, p := range opParams {
		rp := r.doc.ResolveParameter(p)
		merged[paramKey{in: rp.In, name: rp.Name}] = rp
	}
	out := make([]openapi.Parameter, 0, len(merged))
	for _, p := range merged {
		out = append(out, p)
	}
	inOrder := map[string]int{"path": 0, "query": 1, "header": 2, "cookie": 3}
	sort.Slice(out, func(i, j int) bool {
		ri, oki := inOrder[out[i].In]
		if !oki {
			ri = 99
		}
		rj, okj := inOrder[out[j].In]
		if !okj {
			rj = 99
		}
		if ri != rj {
			return ri < rj
		}
		return out[i].Name < out[j].Name
	})
	return out
}

func (r *renderer) parameterType(p openapi.Parameter) string {
	if p.Schema != nil {
		return r.formatType(p.Schema)
	}
	if len(p.Content) > 0 {
		parts := make([]string, 0, len(p.Content))
		for _, ct := range sortedKeys(p.Content) {
			parts = append(parts, fmt.Sprintf("%s (`%s`)", r.formatType(p.Content[ct].Schema), ct))
		}
		return strings.Join(parts, ", ")
	}
	return "any"
}

func (r *renderer) formatResponseContent(content map[string]openapi.MediaType) string {
	if len(content) == 0 {
		return "none"
	}
	parts := make([]string, 0, len(content))
	for _, ct := range sortedKeys(content) {
		mt := content[ct]
		parts = append(parts, fmt.Sprintf("%s (`%s`)", r.formatType(mt.Schema), ct))
	}
	return strings.Join(parts, ", ")
}

func sortedStatuses(responses map[string]openapi.Response) []string {
	keys := make([]string, 0, len(responses))
	for k := range responses {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool {
		ki, kj := keys[i], keys[j]
		if ki == "default" {
			return false
		}
		if kj == "default" {
			return true
		}
		ni, erri := strconv.Atoi(ki)
		nj, errj := strconv.Atoi(kj)
		switch {
		case erri == nil && errj == nil:
			return ni < nj
		case erri == nil:
			return true
		case errj == nil:
			return false
		default:
			return ki < kj
		}
	})
	return keys
}

func (r *renderer) renderSchemaSection(b *strings.Builder, name string, s *openapi.Schema) {
	heading := r.schemaTitles[name]
	if heading == "" {
		heading = name
	}
	fmt.Fprintf(b, "\n### %s\n", heading)

	if s == nil {
		b.WriteString("\n**Type:** any\n")
		return
	}
	if s.Deprecated {
		b.WriteString("\n*(Deprecated)*\n")
	}
	if desc := strings.TrimSpace(s.Description); desc != "" {
		fmt.Fprintf(b, "\n%s\n", desc)
	}
	if s.ExternalDocs != nil && s.ExternalDocs.URL != "" {
		fmt.Fprintf(b, "\n%s\n", formatExternalDocs(s.ExternalDocs))
	}

	// Boolean schema (true / false)
	if s.Boolean != nil {
		fmt.Fprintf(b, "\n**Type:** %s\n", r.formatType(s))
		return
	}

	// Direct $ref alias
	if s.Ref != "" {
		fmt.Fprintf(b, "\n**Type:** %s\n", r.formatType(s))
		return
	}

	// Composition: oneOf
	if len(s.OneOf) > 0 {
		parts := make([]string, 0, len(s.OneOf))
		for _, sub := range s.OneOf {
			parts = append(parts, r.formatType(sub))
		}
		fmt.Fprintf(b, "\n**One of:** %s\n", strings.Join(parts, " | "))
		r.renderDiscriminator(b, s.Discriminator)
		r.renderInlineVariants(b, s.OneOf)
		if len(s.Properties) > 0 {
			b.WriteString("\n")
			r.renderPropertiesTable(b, s)
		}
		return
	}

	// Composition: anyOf
	if len(s.AnyOf) > 0 {
		parts := make([]string, 0, len(s.AnyOf))
		for _, sub := range s.AnyOf {
			parts = append(parts, r.formatType(sub))
		}
		fmt.Fprintf(b, "\n**Any of:** %s\n", strings.Join(parts, " | "))
		r.renderDiscriminator(b, s.Discriminator)
		r.renderInlineVariants(b, s.AnyOf)
		if len(s.Properties) > 0 {
			b.WriteString("\n")
			r.renderPropertiesTable(b, s)
		}
		return
	}

	// Composition: allOf
	if len(s.AllOf) > 0 {
		parts := make([]string, 0, len(s.AllOf))
		mergedProps := make(map[string]*openapi.Schema)
		mergedReq := make(map[string]bool)
		for _, sub := range s.AllOf {
			parts = append(parts, r.formatType(sub))
			if sub != nil && sub.Ref == "" {
				for k, v := range sub.Properties {
					mergedProps[k] = v
				}
				for _, req := range sub.Required {
					mergedReq[req] = true
				}
			}
		}
		for k, v := range s.Properties {
			mergedProps[k] = v
		}
		for _, req := range s.Required {
			mergedReq[req] = true
		}

		fmt.Fprintf(b, "\n**All of:** %s\n", strings.Join(parts, ", "))
		r.renderDiscriminator(b, s.Discriminator)
		if len(mergedProps) > 0 {
			reqList := sortedKeys(mergedReq)
			synthetic := &openapi.Schema{
				Properties:           mergedProps,
				Required:             reqList,
				AdditionalProperties: s.AdditionalProperties,
			}
			b.WriteString("\n")
			r.renderPropertiesTable(b, synthetic)
		}
		return
	}

	// Negation: not
	if s.Not != nil {
		fmt.Fprintf(b, "\n**Type:** %s\n", r.formatType(s))
		return
	}

	// Object schema with properties
	if len(s.Properties) > 0 {
		b.WriteString("\n")
		r.renderPropertiesTable(b, s)
		if s.AdditionalProperties != nil {
			r.renderAdditionalPropertiesNote(b, s.AdditionalProperties)
		}
		r.renderDiscriminator(b, s.Discriminator)
		return
	}

	// Primitive, array, tuple, map, enum, const, or any
	fmt.Fprintf(b, "\n**Type:** %s\n", r.formatType(s))

	var meta []string
	if constraints := formatConstraints(s); len(constraints) > 0 {
		meta = append(meta, "**Constraints:** "+strings.Join(constraints, ", "))
	}
	if s.HasDefault {
		meta = append(meta, "**Default:** "+formatJSONValue(s.Default))
	}
	switch {
	case len(s.Examples) == 1:
		meta = append(meta, "**Example:** "+formatJSONValue(s.Examples[0]))
	case len(s.Examples) > 1:
		ex := make([]string, 0, len(s.Examples))
		for _, e := range s.Examples {
			ex = append(ex, formatJSONValue(e))
		}
		meta = append(meta, "**Examples:** "+strings.Join(ex, ", "))
	case s.HasExample:
		meta = append(meta, "**Example:** "+formatJSONValue(s.Example))
	}
	if len(meta) > 0 {
		b.WriteString("\n")
		for _, m := range meta {
			b.WriteString(m + "\n")
		}
	}
}

func (r *renderer) renderPropertiesTable(b *strings.Builder, s *openapi.Schema) {
	b.WriteString("| Property | Type | Required | Description |\n")
	b.WriteString("| --- | --- | --- | --- |\n")

	for _, propName := range sortedKeys(s.Properties) {
		prop := s.Properties[propName]
		req := "no"
		if slices.Contains(s.Required, propName) {
			req = "yes"
		}
		typ := r.formatType(prop)
		details := formatSchemaDetails("", false, prop, nil, false)
		fmt.Fprintf(b, "| `%s` | %s | %s | %s |\n",
			escapeCell(propName),
			escapeCell(typ),
			req,
			escapeCell(details),
		)
	}
}

func (r *renderer) renderAdditionalPropertiesNote(b *strings.Builder, ap *openapi.AdditionalProperties) {
	if ap == nil {
		return
	}
	if ap.Allowed != nil {
		if !*ap.Allowed {
			b.WriteString("\nAdditional properties are not allowed.\n")
		} else {
			b.WriteString("\n**Additional properties:** any\n")
		}
		return
	}
	if ap.Schema != nil {
		fmt.Fprintf(b, "\n**Additional properties:** %s\n", r.formatType(ap.Schema))
	}
}

func (r *renderer) renderDiscriminator(b *strings.Builder, d *openapi.Discriminator) {
	if d == nil || d.PropertyName == "" {
		return
	}
	fmt.Fprintf(b, "\n**Discriminator:** `%s`\n", d.PropertyName)
	if len(d.Mapping) > 0 {
		b.WriteString("\n| Value | Schema |\n")
		b.WriteString("| --- | --- |\n")
		for _, k := range sortedKeys(d.Mapping) {
			v := d.Mapping[k]
			fmt.Fprintf(b, "| `%s` | %s |\n", escapeCell(k), escapeCell(r.formatRef(v)))
		}
	}
}

func (r *renderer) renderInlineVariants(b *strings.Builder, branches []*openapi.Schema) {
	for i, sub := range branches {
		if sub == nil || sub.Ref != "" || len(sub.Properties) == 0 {
			continue
		}
		label := fmt.Sprintf("Variant %d", i+1)
		if sub.Title != "" {
			label = sub.Title
		}
		fmt.Fprintf(b, "\n**%s**\n\n", label)
		r.renderPropertiesTable(b, sub)
	}
}
